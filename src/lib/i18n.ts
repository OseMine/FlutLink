export const LANG_KEY = "flutlink.lang";

export function currentLang(): Lang {
  try {
    const raw = localStorage.getItem(LANG_KEY);
    if (!raw) return "en";
    const parsed = JSON.parse(raw) as Lang;
    return parsed === "de" ? "de" : "en";
  } catch {
    return "en";
  }
}

